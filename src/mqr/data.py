"""Tokenization and reproducible next-token batches for local experiments."""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Iterable

import numpy as np
import torch


@dataclass(frozen=True)
class ByteTokenizer:
    """UTF-8 bytes for smoke tests; this is not the research BPE tokenizer."""

    vocab_size: int = 259
    pad_id: int = 256
    eos_id: int = 257
    bos_id: int = 258

    def __post_init__(self) -> None:
        if (self.vocab_size, self.pad_id, self.eos_id, self.bos_id) != (
            259, 256, 257, 258
        ):
            raise ValueError("ByteTokenizer uses 256 bytes followed by PAD/EOS/BOS IDs.")

    def encode(self, text: str, add_eos: bool = True) -> list[int]:
        ids = list(text.encode("utf-8"))
        return ids + [self.eos_id] if add_eos else ids

    def decode(self, ids: Iterable[int]) -> str:
        values: list[int] = []
        for token_id in ids:
            token_id = int(token_id)
            if not 0 <= token_id < self.vocab_size:
                raise ValueError(f"Invalid byte token ID: {token_id}")
            if token_id < 256:
                values.append(token_id)
        # Arbitrary generated byte strings may end inside a UTF-8 character.
        return bytes(values).decode("utf-8", errors="replace")

    def save(self, path: str | Path) -> None:
        Path(path).write_text(
            json.dumps({"kind": "utf8_bytes", **asdict(self)}, indent=2) + "\n",
            encoding="utf-8",
        )


class BPETokenizer:
    """Small adapter around an optional Hugging Face Tokenizers artifact."""

    def __init__(self, tokenizer: object) -> None:
        self.tokenizer = tokenizer
        self.vocab_size = tokenizer.get_vocab_size()
        self.pad_id = tokenizer.token_to_id("<|pad|>")
        self.eos_id = tokenizer.token_to_id("<|eos|>")
        self.bos_id = tokenizer.token_to_id("<|bos|>")
        if None in (self.pad_id, self.eos_id, self.bos_id):
            raise ValueError("BPE tokenizer must define PAD, EOS and BOS tokens.")
        # Literal special-token spellings in corpus text remain ordinary text.
        tokenizer.encode_special_tokens = True

    def encode(self, text: str, add_eos: bool = True) -> list[int]:
        ids = self.tokenizer.encode(text, add_special_tokens=False).ids
        return ids + [self.eos_id] if add_eos else ids

    def decode(self, ids: Iterable[int]) -> str:
        return self.tokenizer.decode([int(value) for value in ids], skip_special_tokens=True)

    def save(self, path: str | Path) -> None:
        self.tokenizer.save(str(path))


def load_tokenizer(path: str | Path) -> ByteTokenizer | BPETokenizer:
    """Read our byte descriptor or a Tokenizers JSON without downloading anything."""
    path = Path(path)
    descriptor = json.loads(path.read_text(encoding="utf-8"))
    if descriptor.get("kind") == "utf8_bytes":
        return ByteTokenizer(**{key: descriptor[key] for key in asdict(ByteTokenizer())})
    try:
        from tokenizers import Tokenizer
    except ImportError as exc:
        raise ImportError("Install the 'tokenizers' package to load BPE data.") from exc
    return BPETokenizer(Tokenizer.from_file(str(path)))


class TokenStream:
    """Packed documents separated by EOS; windows can cross document boundaries.

    A .npy source remains memory mapped. Sampling copies only selected windows,
    never the complete corpus. Use separate files for each held-out split.
    """

    _CHUNK_SIZE = 1_048_576

    def __init__(
        self,
        tokens: torch.Tensor | np.ndarray,
        context_length: int,
        vocab_size: int | None = None,
    ) -> None:
        if not isinstance(context_length, int) or isinstance(context_length, bool) or context_length < 1:
            raise ValueError("context_length must be a positive integer.")
        if isinstance(tokens, torch.Tensor):
            if tokens.dtype not in (torch.uint8, torch.int8, torch.int16, torch.int32, torch.int64):
                raise ValueError("Tokens must have an integer dtype.")
            tokens = tokens.detach().cpu().clone().numpy()
        if not isinstance(tokens, np.ndarray) or tokens.ndim != 1:
            raise ValueError("Tokens must be a one-dimensional tensor or NumPy array.")
        if tokens.dtype.kind not in "ui":
            raise ValueError("Tokens must have an integer dtype.")
        if len(tokens) < context_length + 1:
            raise ValueError("Token stream needs at least context_length + 1 tokens.")
        self.tokens = tokens
        self.context_length = context_length
        self.num_tokens = len(tokens)
        self._fingerprint: str | None = None
        self.max_token_id = 0
        for offset in range(0, self.num_tokens, self._CHUNK_SIZE):
            chunk = tokens[offset : offset + self._CHUNK_SIZE]
            minimum, maximum = int(chunk.min()), int(chunk.max())
            if minimum < 0 or maximum > np.iinfo(np.uint32).max:
                raise ValueError("Token IDs must fit unsigned 32-bit integers.")
            self.max_token_id = max(self.max_token_id, maximum)
        if vocab_size is not None and (vocab_size < 1 or self.max_token_id >= vocab_size):
            raise ValueError("Token ID is outside the configured vocabulary.")

    def __len__(self) -> int:
        return self.num_tokens

    @classmethod
    def from_file(
        cls,
        path: str | Path,
        context_length: int,
        vocab_size: int | None = None,
    ) -> TokenStream:
        path = Path(path)
        if path.suffix != ".npy":
            raise ValueError("Prepared token files must be .npy arrays, with a dtype and shape header.")
        return cls(np.load(path, mmap_mode="r", allow_pickle=False), context_length, vocab_size)

    @classmethod
    def from_text(
        cls,
        path: str | Path,
        context_length: int,
        tokenizer: ByteTokenizer | BPETokenizer | None = None,
    ) -> TokenStream:
        tokenizer = tokenizer or ByteTokenizer()
        text = Path(path).read_bytes().decode("utf-8")
        return cls(
            np.asarray(tokenizer.encode(text), dtype=np.uint32),
            context_length,
            tokenizer.vocab_size,
        )

    @property
    def fingerprint(self) -> str:
        """SHA-256 of canonical little-endian uint32 token IDs, independent of dtype."""
        if self._fingerprint is None:
            digest = hashlib.sha256()
            for offset in range(0, self.num_tokens, self._CHUNK_SIZE):
                chunk = self.tokens[offset : offset + self._CHUNK_SIZE]
                digest.update(np.asarray(chunk, dtype="<u4").tobytes())
            self._fingerprint = digest.hexdigest()
        return self._fingerprint

    def sample(
        self, batch_size: int, generator: torch.Generator
    ) -> tuple[torch.Tensor, torch.Tensor]:
        if not isinstance(batch_size, int) or isinstance(batch_size, bool) or batch_size < 1:
            raise ValueError("batch_size must be a positive integer.")
        if generator.device.type != "cpu":
            raise ValueError("TokenStream sampling requires a CPU torch.Generator.")
        starts = torch.randint(
            self.num_tokens - self.context_length,
            (batch_size,),
            generator=generator,
        ).tolist()
        windows = np.stack(
            [self.tokens[start : start + self.context_length + 1] for start in starts]
        ).astype(np.int64, copy=False)
        return (
            torch.from_numpy(windows[:, :-1].copy()),
            torch.from_numpy(windows[:, 1:].copy()),
        )
